# define a function to replace '[]' with an empty list in dict
def replace_list(dic):
    for key in dic.keys():
        if type(dic[key]) is dict:
            replace_list(dic[key])
        else:
            if dic[key] == '[]':
                dic[key] = []

# define a function to reformalize the property
def reformalize_property(propertyValue: str):
    if len(propertyValue) != 0:
        if (propertyValue[0] == '[' and propertyValue[-1] == ']') or (propertyValue[0] == '{' and propertyValue[-1] == '}'):
            start = propertyValue.find('<')
            end = propertyValue[::-1].find('>')
            if start == -1 and end == -1:
                try:
                    return json.loads(propertyValue.replace('\'\'\'', '\'').replace('\'', '\"').replace('\"[', '[').replace(']\"', ']'))
                except:
                    return propertyValue[1:-1].split(', ')
            else:
                try:
                    return json.loads(propertyValue[:start].replace('\'', '\"') + propertyValue[start:-end] + propertyValue[-end:].replace('\'', '\"'))
                except:
                    return 'XML Decoding Failed !'
        else:
            try:
                return float(propertyValue)
            except:
                return propertyValue
    else:
        return propertyValue

