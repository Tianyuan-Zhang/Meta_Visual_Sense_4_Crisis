# define a function to get the names of the properties of a node
def get_properties_names_node(tx, node: int) -> list[str]:
    keys = []
    result= tx.run(
        'MATCH (n) WHERE ID(n) = ' + str(node) +
        ' RETURN KEYS(n)'
    )
    for record in result:
        keys = record.value()
        break
    return keys

# define a function to get the properties of a node
def get_properties_node(tx, node: int) -> dict:
    keys = get_properties_names_node(tx, node)
    properties = {}
    for key in keys:
        result = tx.run(
            'MATCH (n) WHERE ID(n) = ' + str(node) +
            ' RETURN n.`' + key + '`'
        )
        for record in result:
            properties[key] = reformalize_property(record.value())
            break
    replace_list(properties)
    return properties

# define a function to get a specific property of a node based on the name of the property
def get_property_node(tx, node: int, name: str):
    keys = get_properties_names_node(tx, node)
    if name not in keys:
        return 'The property doesn\'t exist!'
    else:
        result = tx.run(
            'MATCH (n) WHERE ID(n) = ' + str(node) +
            ' RETURN n.`' + name + '`'
        )
        for record in result:
            value = reformalize_property(record.value())
            break
        if type(value) is dict:
            replace_list(value)
        return value

# define a function to create a node and return its identity
def create_node(tx, labels: list[str], properties: dict) -> int:
    result = tx.run(
        'CREATE (n:instance) RETURN ID(n)'
    )
    for record in result:
        node = int(record.value())
        break
    for label in labels:
        set_label_node(tx, node, label)
    for key, value in properties.items():
        set_property_node(tx, node, key, value)
    return node

# define a function to encode the property 'propertyLabels'
def encode_property_labels(propertyLabels) -> str:
    '''
    propertyLabels should be a list of labels
    '''
    temp = []
    for label in propertyLabels:
        temp.append([{'name': 'label', 'value': label}])
    return json.dumps(temp).replace('\"', '\'')

# define a function to encode the property 'geolocation'
def encode_geolocation(nodeType, point = None) -> str:
    '''
    point should be a list of latitude, longitude, altitude
    '''
    temp = {'itemView': [{}]}
    if (nodeType != 'Territory') and (point != None):
        temp['itemView'][0]['point'] = {
            'latitude': point[0],
            'longitude': point[1],
            'altitude': point[2]
        }
    if nodeType == 'Territory':
        temp['itemView'][0]['area'] = {
            'strokeColor': '#D8BFD8',
            'strokeWidth': 3.0,
            'strokeOpacity': 0.4,
            'fillColor': '#D8BFD8',
            'fillOpacity': 0.4
        }
    return json.dumps(temp).replace('\"', '\'')

# define a function to generate relatively position in the panel
def position_generator():
    a, b, c, d = 0, 0, 0, 0
    panel = (yield [0.0, 0.0])
    while True:
        if panel == 'Objectives':
            x = (a % 10 + 0.5) * 120.0
            y = (a // 10 + 0.5) * 120.0
            a += 1
            panel = (yield [x, y])
        elif panel == 'Collaborative process':
            x = (b % 10 + 0.5) * 120.0
            y = (b // 10 + 0.5) * 120.0
            b += 1
            panel = (yield [x, y])
        elif panel == 'Context':
            x = (c % 10 + 0.5) * 120.0
            y = (c // 10 + 0.5) * 120.0
            c += 1
            panel = (yield [x, y])
        elif panel == 'Context and partners':
            x = (d % 10 + 0.5) * 120.0
            y = (d // 10 + 0.5) * 120.0
            d += 1
            panel = (yield [x, y])

