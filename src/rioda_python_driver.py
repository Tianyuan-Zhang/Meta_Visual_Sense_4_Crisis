# define a function to get the properties of an edge
def get_properties_edge(tx, edge: int) -> dict:
    properties = {}
    result = tx.run(
        'MATCH ()-[r]->() WHERE ID(r) = ' + str(edge) +
        ' RETURN r'
    )
    for record in result:
        temp = record.value()
        break
    keys = temp.keys()
    for key in keys:
        properties[key] = reformalize_property(temp.get(key))
    return properties

# define a function to get a specific property of an edge based on the name of the property
def get_property_edge(tx, edge: int, name: str):
    keys = get_properties_names_edge(tx, edge)
    if name not in keys:
        return 'The property doesn\'t exist!'
    else:
        result = tx.run(
            'MATCH ()-[r]-() WHERE ID(r) = ' + str(edge) +
            ' RETURN r.`' + name + '`'
        )
        for record in result:
            value = reformalize_property(record.value())
            break
        if type(value) is dict:
            replace_list(value)
        return value

# define a function to set a property to an edge
def set_property_edge(tx, edge: int, property_name: str, propertyValue):
    tx.run(
        'MATCH ()-[r]->(b) WHERE ID(r) = ' + str(edge) +
        ' SET r.' + property_name + ' = \"' + str(propertyValue) + '\"'
    )

# define a function to create an edge between two nodes
def create_edge(
    tx,
    currentKnowledgeSpaceName: str,
    currentCollaborationName: str,
    start: int,
    end: int,
    edgeType: str,
    properties = None
) -> int:
    result = tx.run(
        'MATCH (a), (b) WHERE id(a) = ' + str(start) + ' and id(b) = ' + str(end) +
        ' CREATE (a)-[r:`' + EDGE_TYPE[edgeType] + '`]->(b) RETURN ID(r)'
    )
    for record in result:
        edge = int(record.value())
        break
    edgeId = generate_edge_id(currentKnowledgeSpaceName, currentCollaborationName)
    set_property_edge(tx, edge, 'modelEdgeId', edgeId)
    set_property_edge(tx, edge, 'property_name', edgeType)
    if properties:
        for key, value in properties.items():
            set_property_edge(tx, edge, key, value)
    brokenEdge = {
        'edge': {
            'id': edgeId[:41],
            'type': EDGE_TYPE[edgeType],
            'source': get_property_node(tx, start, 'modelNodeId')[:41],
            'property': [{
                'name': 'name',
                'value': edgeType
            }]
        },
        'sourceId': get_property_node(tx, start, 'modelNodeId')[:41],
        'targetId': get_property_node(tx, end, 'modelNodeId')[:41]
    }
    if properties:
        for key, value in properties.items():
            brokenEdge['edge']['property'].append({
                'name': key[9:],
                'value': value
            })
    brokenEdges = get_property_node(tx, start, 'brokenEdges')
    if brokenEdges == 'The property doesn\'t exist!':
        brokenEdges = {'brokenEdge': []}
    else:
        if not 'brokenEdge' in brokenEdges.keys():
            brokenEdges['brokenEdge'] = []
    brokenEdges['brokenEdge'].append(brokenEdge)
    set_property_node(tx, start, 'brokenEdges', json.dumps(brokenEdges).replace('\"', '\''))
    return edge

# define a function to delete an edge based on given id
def delete_edge(tx, id: int):
    result = tx.run(
        'MATCH (a)-[r]->(b) WHERE ID(r)=' + str(id) + ' RETURN ID(a)'
    )
    for record in result:
        start = int(record.value())
        break
    edgeId = get_property_edge(tx, id, 'modelEdgeId')
    brokenEdges = get_property_node(tx, start, 'brokenEdges')
    if brokenEdges:
        if 'brokenEdge' in brokenEdges.keys():
            for edge in brokenEdges['brokenEdge']:
                if edge['edge']['id'] == edgeId[:41]:
                    brokenEdges['brokenEdge'].remove(edge)
                    set_property_node(tx, start, 'brokenEdges', json.dumps(brokenEdges).replace('\"', '\''))
    tx.run(
        'MATCH (a)-[r]->(b) WHERE ID(r)=' + str(id) + ' DELETE r'
    )

